// Generates packages/shared/src/fontCoverage.ts: for each certificate font, the characters in the
// supported Unicode ranges that the font has no glyph for. The browser can't inspect a font's
// glyphs, so this table is how the preview and the PDF renderer agree on fallback decisions.
// Usage: pnpm --filter @certdrop/api fonts:coverage   (re-run whenever a font file changes)
import fontkit from '@pdf-lib/fontkit';
import { CERT_FONT_META, SUPPORTED_RANGES } from '@certdrop/shared';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../../..');
const FONTS = path.join(ROOT, 'packages/shared/fonts');
const OUT = path.join(ROOT, 'packages/shared/src/fontCoverage.ts');

/** Code points the renderer could be asked to draw (combining marks are composed by NFC first). */
export function candidateCodePoints(): number[] {
  const points: number[] = [];
  for (const [lo, hi] of SUPPORTED_RANGES) {
    for (let cp = lo; cp <= hi; cp++) {
      const char = String.fromCodePoint(cp);
      if (/\p{L}|\p{N}|\p{P}|\p{S}/u.test(char)) points.push(cp);
    }
  }
  return points;
}

/** Collapses sorted code points into "a-b" range strings to keep the generated file small. */
export function toRanges(points: number[]): Array<[number, number]> {
  const ranges: Array<[number, number]> = [];
  for (const cp of points) {
    const last = ranges.at(-1);
    if (last && cp === last[1] + 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}

export function computeCoverage(): Record<string, Array<[number, number]>> {
  const candidates = candidateCodePoints();
  const result: Record<string, Array<[number, number]>> = {};
  for (const meta of Object.values(CERT_FONT_META)) {
    const font = fontkit.create(readFileSync(path.join(FONTS, meta.file)));
    result[meta.id] = toRanges(candidates.filter((cp) => !font.hasGlyphForCodePoint(cp)));
  }
  return result;
}

if (process.argv[1] && import.meta.filename === path.resolve(process.argv[1])) {
  const coverage = computeCoverage();
  const body = Object.entries(coverage)
    .map(([id, ranges]) => `  '${id}': ${JSON.stringify(ranges)},`)
    .join('\n');
  writeFileSync(
    OUT,
    `// Generated by apps/api/scripts/font-coverage.ts. Do not edit by hand.\n` +
      `// Code-point ranges each font has no glyph for, within SUPPORTED_RANGES.\n` +
      `import type { CertFont } from './layout';\n\n` +
      `export const MISSING_GLYPHS: Record<CertFont, ReadonlyArray<readonly [number, number]>> = {\n${body}\n};\n`,
  );
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}
